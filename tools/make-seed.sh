#!/bin/bash
# Makes a release tarball with the bootstrap seed: rice's own source, the
# front end's source, the source of the packages rice uses, and the C that
# rice generates for itself (seed/), so `make from-seed` can build rice
# with just a C compiler and the front end (src/bootstrap-plan.md, Phase D).
#
# The seed is generated from the tarball's own source, not the working
# tree: the committed tree (git archive HEAD) is staged first, and rice
# compiles Rice.Main there. So commit before making a release.
#
# Usage: tools/make-seed.sh [RICE]
#   RICE   the rice that generates the seed (default: rice on $PATH, or
#          ~/.cpm/bin/rice)
#
# Writes rice-<version>.tar.xz in the current directory. Takes a few
# minutes (rice compiling Rice.Main from scratch) and about 3 GB.
set -eu
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RICE="${1:-$(command -v rice || echo "$HOME/.cpm/bin/rice")}"
VERSION="$(sed -n 's/^ *"version": *"\(.*\)",$/\1/p' "$ROOT/package.json")"
NAME="rice-$VERSION"
OUT="$PWD/$NAME.tar.xz"

if [ -n "$(git -C "$ROOT" status --porcelain --untracked-files=no)" ]; then
  echo "make-seed: the working tree has uncommitted changes; the tarball" >&2
  echo "           is made from HEAD, so they wouldn't be in it." >&2
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
STAGE="$WORK/$NAME"
mkdir -p "$STAGE"

echo "== staging $NAME from HEAD"
git -C "$ROOT" archive HEAD | tar -x -C "$STAGE"
mkdir -p "$STAGE/frontend"
git -C "$ROOT/frontend" archive HEAD | tar -x -C "$STAGE/frontend"
# The packages rice is built from (cypm's .cpm/packages, which git
# ignores): just their sources and package.json.
for p in "$ROOT"/.cpm/packages/*/; do
  name="$(basename "$p")"
  mkdir -p "$STAGE/.cpm/packages/$name"
  cp "$p/package.json" "$STAGE/.cpm/packages/$name/"
  rsync -a --exclude .curry "$p/src" "$STAGE/.cpm/packages/$name/"
done
# Generated by cypm, and ignored by git, but part of rice's source.
cp "$ROOT/src/Rice/PackageConfig.curry" "$STAGE/src/Rice/"

echo "== compiling Rice.Main with $RICE"
# A copy to compile in, so the caches it leaves don't go in the tarball.
BUILD="$WORK/build"
cp -R "$STAGE" "$BUILD"
LOADPATH="$(sed -n 's/^packageLoadPath = "\(.*\)"$/\1/p' \
              "$BUILD/src/Rice/PackageConfig.curry" | sed "s|$ROOT|$BUILD|g")"
( cd "$BUILD/src" && RICEHOME="$BUILD" CURRYPATH="$LOADPATH" "$RICE" -v Rice.Main ) \
  > "$WORK/build.log" 2>&1 || { cat "$WORK/build.log"; exit 1; }

echo "== collecting the seed"
SEED="$STAGE/seed"
mkdir -p "$SEED/gen"
# Every generated .c and .h, at its path under its module directory's
# .curry/rice-<version>/, which is the path #include uses for it. Module
# names are unique, so these don't collide.
( cd "$BUILD" && find . -path "*/.curry/rice-$VERSION/*" \( -name '*.c' -o -name '*.h' \) \
    -not -path '*/obj-*' -not -name rice-main.c ) |
while read -r f; do
  rel="${f#*/.curry/rice-$VERSION/}"
  mkdir -p "$SEED/gen/$(dirname "$rel")"
  cp "$BUILD/$f" "$SEED/gen/$rel"
done
cp "$BUILD/src/.curry/rice-$VERSION/rice-main.c" "$SEED/"
# The runtime's externals the link used: runtime/ext/obj-<hash>/M.o.
grep '^Linking:' "$WORK/build.log" | tr ' ' '\n' | grep '/runtime/ext/obj-' |
  sed 's|.*/\([^/]*\)\.o$|\1|' | sort > "$SEED/ext.txt"
{
  echo "Generated by $("$RICE" --help >/dev/null 2>&1 && echo "$RICE")"
  echo "from commit $(git -C "$ROOT" rev-parse HEAD)"
  echo "on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
} > "$SEED/README"
echo "   $(find "$SEED/gen" -name '*.c' | wc -l | tr -d ' ') C files," \
     "$(wc -l < "$SEED/ext.txt" | tr -d ' ') externals files"

echo "== writing $OUT"
tar -C "$WORK" -cJf "$OUT" "$NAME"
echo "   $(du -h "$OUT" | cut -f1)"
